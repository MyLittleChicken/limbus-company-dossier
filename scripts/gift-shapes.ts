/**
 * 하나를 분류한다.
 *
 * **우선순위가 곧 「절 나누기를 누가 지배하는가」다.** 티어가 있으면 티어가
 * 전체 구조를 정하고, 없으면 게이트가, 없으면 머리가, 없으면 강화가 정한다.
 */
export function classifyGift(desc: string): GiftShape {
	const ps = paras(desc);
	const first = ps[0] ?? '';
	const rest = ps.slice(1);

	const traits: string[] = [];
	const tier = /기프트 효과 강화/.test(desc);
	const gate = isGate(first);
	const head = isHead(first);
	const amp = hasAmp(rest) || (ps.length === 1 && hasAmp(ps));

	if (tier) { if (gate) traits.push('GATE'); if (head) traits.push('HEAD'); if (amp) traits.push('AMP'); return { klass: 'TIER', traits, paras: ps.length }; }
	if (gate) { if (head) traits.push('HEAD'); if (amp) traits.push('AMP'); return { klass: 'GATE', traits, paras: ps.length }; }
	if (head) { if (amp) traits.push('AMP'); return { klass: 'HEAD', traits, paras: ps.length }; }
	if (amp) return { klass: 'AMP', traits, paras: ps.length };
	if (ps.length >= 2) return { klass: 'INDEP', traits, paras: ps.length };
	return { klass: 'SINGLE', traits, paras: ps.length };
}
